import { spawn, spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, copyFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';

const env = { ...process.env, NO_COLOR: '1' };
delete env.FORCE_COLOR;
const output = [`Verification run: ${new Date().toISOString()}\nNode: ${process.version}\n`];
function run(title, args, extraEnv = env) {
  console.log(`\n${title}`);
  const result = spawnSync(process.execPath, args, {
    env: extraEnv,
    encoding: 'utf8',
    timeout: 120000,
  });
  const text = (result.stdout ?? '') + (result.stderr ?? '');
  output.push(`\n${title}\n$ node ${args.join(' ')}\n${text}`);
  process.stdout.write(text);
  writeFileSync('docs/test-results.txt', output.join('\n'));
  if (result.status !== 0)
    throw new Error(
      `${title} failed (${result.status}): ${result.error?.message ?? 'see output above'}`,
    );
  return text;
}

run('Formatting', ['node_modules/prettier/bin/prettier.cjs', '--check', '.']);
const apiOutput = run('Backend tests and coverage', [
  'node_modules/vitest/vitest.mjs',
  'run',
  '--coverage',
]);
run('TypeScript checks', ['node_modules/typescript/bin/tsc', '--noEmit']);
run('Frontend production build', ['node_modules/vite/bin/vite.js', 'build']);
run('Backend production build', ['node_modules/typescript/bin/tsc', '-p', 'tsconfig.server.json']);
run('Browser tests', ['node_modules/@playwright/test/cli.js', 'test']);

const directory = mkdtempSync(join(tmpdir(), 'motorstock-production-'));
const productionEnv = {
  ...env,
  PORT: '3003',
  DATABASE_PATH: join(directory, 'smoke.db'),
  JWT_SECRET: 'isolated-production-smoke-secret-at-least-32-characters',
  SEED_ADMIN_EMAIL: 'admin@demo.local',
  SEED_ADMIN_PASSWORD: 'AdminDemo123!',
  SEED_CUSTOMER_EMAIL: 'customer@demo.local',
  SEED_CUSTOMER_PASSWORD: 'CustomerDemo123!',
};
let server;
try {
  run('Compiled seed command', ['dist/server/seed.js'], productionEnv);
  server = spawn(process.execPath, ['dist/server/index.js'], {
    env: productionEnv,
    stdio: 'ignore',
  });
  const base = 'http://127.0.0.1:3003';
  let ready = false;
  for (let attempt = 0; attempt < 50; attempt++) {
    try {
      ready = (await fetch(`${base}/api/health`)).ok;
      if (ready) break;
    } catch {}
    await new Promise((resolve) => setTimeout(resolve, 100));
  }
  assert(ready, 'production server becomes healthy');
  const html = await (await fetch(base)).text();
  assert(html.includes('<div id="root"></div>'), 'compiled SPA is served');
  const asset = html.match(/src="([^" ]+\.js)"/)?.[1];
  assert(asset && (await fetch(base + asset)).ok, 'compiled JavaScript asset is served');
  const login = await fetch(`${base}/api/auth/login`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: 'admin@demo.local', password: 'AdminDemo123!' }),
  });
  assert.equal(login.status, 200);
  const { token } = await login.json();
  const catalogue = await fetch(`${base}/api/vehicles`, {
    headers: { Authorization: `Bearer ${token}` },
  });
  assert.equal(catalogue.status, 200);
  assert.equal((await catalogue.json()).vehicles.length, 6);
  output.push(
    '\nProduction HTTP smoke check: PASS (health, HTML, JS asset, login and protected catalogue).\n',
  );
  console.log('Production HTTP smoke check: PASS');
} finally {
  if (server && server.exitCode === null) {
    const exited = new Promise((resolve) => server.once('exit', resolve));
    server.kill();
    await exited;
  }
  rmSync(directory, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
  writeFileSync('docs/test-results.txt', output.join('\n'));
}

const coverage = JSON.parse(readFileSync('coverage/coverage-summary.json', 'utf8')).total;
const browser = JSON.parse(readFileSync('test-results/e2e-results.json', 'utf8')).stats;
const count = apiOutput.match(/Tests\s+(\d+) passed/)?.[1] ?? 'See captured output';
copyFileSync('coverage/coverage-summary.json', 'docs/coverage-summary.json');
const date = new Intl.DateTimeFormat('en-IN', {
  dateStyle: 'long',
  timeStyle: 'long',
  timeZone: 'Asia/Kolkata',
}).format(new Date());
writeFileSync(
  'docs/TEST_REPORT.md',
  `# Test report\n\nGenerated by \`pnpm verify\` on ${date}.\n\n| Check | Result |\n| --- | --- |\n| API/config tests | ${count} passed |\n| Chromium browser tests | ${browser.expected} passed, ${browser.unexpected} failed, ${browser.skipped} skipped |\n| TypeScript | Pass |\n| Frontend + backend production build | Pass |\n| Compiled seed and production HTTP smoke check | Pass |\n| Formatting | Pass |\n\n| Backend coverage | Percentage |\n| --- | ---: |\n| Statements | ${coverage.statements.pct}% |\n| Branches | ${coverage.branches.pct}% |\n| Functions | ${coverage.functions.pct}% |\n| Lines | ${coverage.lines.pct}% |\n\nCoverage includes application modules and configuration; process bootstrap and seed are excluded from unit coverage and exercised by the production smoke check. API tests use temporary on-disk databases, not an in-memory substitute. Browser tests use an isolated seeded database and real HTTP requests. This run uses Chromium; no cross-browser or load-test claim is made.\n\nThe production dependency audit was run separately with \`pnpm audit --prod\` and found no known vulnerabilities at development time. Docker was not executed because the local Docker engine was unavailable. GitHub Actions results are separate from these local results.\n\n[Raw command output](test-results.txt) · [Coverage data](coverage-summary.json)\n`,
);
// Keep generated Markdown and JSON consistent with the repository formatter.
run('Format generated report', [
  'node_modules/prettier/bin/prettier.cjs',
  '--write',
  'docs/TEST_REPORT.md',
  'docs/coverage-summary.json',
]);
console.log('\nAll verification checks passed. Reports saved in docs/.');
